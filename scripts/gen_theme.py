# Generates web/theme.css: OKLCH scales for every hue, dark and light, as "L C H" triples
from pathlib import Path
SHADES = [50,100,200,300,400,500,600,700,800,900,950]
HUES = {  # name: (hue, peak chroma)
    "n": (175, 0.014),     # ledger grey-green neutral
    "ink": (266, 0.15),    # cheque-ink blue accent
    "safe": (158, 0.13),
    "loss": (27, 0.17),
    "hold": (72, 0.14),
}
DARK_N  = dict(zip(SHADES,[.97,.94,.89,.80,.70,.58,.47,.38,.30,.225,.185]))
LIGHT_N = dict(zip(SHADES,[.20,.25,.30,.37,.47,.56,.66,.80,.885,.995,.968]))
DARK_C  = dict(zip(SHADES,[.97,.93,.88,.81,.73,.64,.52,.44,.35,.27,.215]))
LIGHT_C = dict(zip(SHADES,[.24,.29,.34,.40,.46,.56,.52,.83,.89,.935,.965]))

def chroma(L, peak):
    return round(peak * max(0.22, 1 - abs(L - 0.6) * 1.6), 4)

def block(lmap_n, lmap_c):
    out = []
    for name, (h, c) in HUES.items():
        lm = lmap_n if name == "n" else lmap_c
        for s in SHADES:
            out.append(f"  --{name}-{s}: {lm[s]:.3f} {chroma(lm[s], c)} {h};")
    return "\n".join(out)

css = f"""/* Ladon theme: generated by scripts/gen_theme.py. Every colour is an OKLCH "L C H" triple,
   so Tailwind and plain CSS both use oklch(var(--x) / alpha). Dark is the default look;
   light redefines the same tokens. */
:root {{
{block(DARK_N, DARK_C)}
  --hi: 0.985 0.004 175;
  color-scheme: dark;
}}
@media (prefers-color-scheme: light) {{
  :root:not([data-theme="dark"]) {{
{block(LIGHT_N, LIGHT_C)}
  --hi: 0.17 0.01 175;
  color-scheme: light;
  }}
}}
:root[data-theme="light"] {{
{block(LIGHT_N, LIGHT_C)}
  --hi: 0.17 0.01 175;
  color-scheme: light;
}}
:root {{
  --font-display: "Archivo", "Arial Narrow", system-ui, sans-serif;
  --font-body: "Public Sans", system-ui, -apple-system, "Segoe UI", sans-serif;
  --font-mono: "IBM Plex Mono", ui-monospace, "SFMono-Regular", Menlo, monospace;
}}
html {{ background: oklch(var(--n-950)); color: oklch(var(--n-100)); }}
body {{ font-family: var(--font-body); font-variant-numeric: tabular-nums; }}
::selection {{ background: oklch(var(--ink-500) / 0.35); }}
::-webkit-scrollbar {{ width: 8px; height: 8px; }}
::-webkit-scrollbar-track {{ background: transparent; }}
::-webkit-scrollbar-thumb {{ background: oklch(var(--n-700)); border-radius: 4px; }}
:focus-visible {{ outline: 2px solid oklch(var(--ink-400)); outline-offset: 2px; }}
@media (prefers-reduced-motion: reduce) {{ *, *::before, *::after {{ animation: none !important; transition: none !important; }} }}
"""
open(Path(__file__).resolve().parent.parent / "web" / "theme.css", "w").write(css)
